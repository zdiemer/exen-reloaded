#!/usr/bin/env python3
"""Generate src/core/natives_gen.h from the framework in vendor/gensimu/gensimu.exe.

Usage: python tools/gen_natives.py [gensimu.exe] [out.h]

The table maps each native index (the u32 stored at a native method's code offset, an index
into gensimu's function table at VA 0x457c08) to the declaring class, name and descriptor,
plus the argument and return sizes in VM words. The C native layer is keyed on this table, so
regenerate it rather than editing it.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cvp  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def ret_words(desc: str) -> int:
    r = desc[desc.index(")") + 1:]
    return 0 if r == "V" else 2 if r == "J" else 1


def ident(s: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in s)


def main(argv: list[str]) -> int:
    exe = Path(argv[0]) if argv else ROOT / "vendor/gensimu/gensimu.exe"
    out = Path(argv[1]) if len(argv) > 1 else ROOT / "src/core/natives_gen.h"
    _, blob = cvp.load_image(exe)
    classes = cvp.parse_image(blob)
    uni = cvp.Universe(classes)
    rows: dict[int, tuple] = {}
    for c in classes:
        for m in c.methods:
            if m.native_index is None:
                continue
            desc = uni.descriptor(c, m)
            if desc is None:
                raise SystemExit(f"no debug descriptor for native {c.name}.{m.hash:08x}")
            if m.native_index in rows:
                raise SystemExit(f"duplicate native index {m.native_index}")
            rows[m.native_index] = (c.name, m.name, desc, m.hash, bool(m.flags & 8),
                                    m.argc, ret_words(desc))
    n = max(rows) + 1
    missing = [i for i in range(n) if i not in rows]
    lines = [
        "/* Generated by tools/gen_natives.py from vendor/gensimu/gensimu.exe. Do not edit. */",
        "#ifndef EXEN_NATIVES_GEN_H",
        "#define EXEN_NATIVES_GEN_H",
        "",
        f"#define EXEN_NATIVE_COUNT {n}",
        "",
        "/* X(index, id, class, name, descriptor, member_hash, is_static, arg_words, ret_words) */",
        "#define EXEN_NATIVES(X) \\",
    ]
    for i in range(n):
        if i in rows:
            cls, name, desc, h, st, argc, rw = rows[i]
            nid = ident(cls.split(".")[-1]) + "_" + ident(name)
            lines.append(f'    X({i}, {nid}_{i}, "{cls}", "{name}", "{desc}", 0x{h:08x}u, '
                         f'{int(st)}, {argc}, {rw}) \\')
    lines += ["", "#endif", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out}: {len(rows)} natives, indices 0..{n - 1}"
          + (f", gaps {missing}" if missing else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
