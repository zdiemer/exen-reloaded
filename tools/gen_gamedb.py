#!/usr/bin/env python3
"""Generate src/core/gamedb_gen.h from data/gamedb.tsv (per-game defaults such as the handset
screen size). Usage: python tools/gen_gamedb.py"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def cstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


rows = []
for line in (ROOT / "data/gamedb.tsv").read_text(encoding="utf-8").splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    crc, main, title, w, h, basis = line.split("\t")
    rows.append(f"    {{0x{crc}u, {cstr(main)}, {cstr(title)}, {int(w)}, {int(h)}}},")
out = ROOT / "src/core/gamedb_gen.h"
out.write_text("/* Generated by tools/gen_gamedb.py from data/gamedb.tsv. Do not edit. */\n"
               "static const GameDbEntry gamedb[] = {\n" + "\n".join(rows) + "\n};\n",
               encoding="utf-8", newline="\n")
print(f"wrote {out}: {len(rows)} games")
